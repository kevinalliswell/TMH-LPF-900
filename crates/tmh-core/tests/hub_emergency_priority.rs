//! Deterministic emergency scheduling/latching reproductions on 307718f.
//! Real DeviceHub threads and MfcActor; the fake only controls wire boundaries.
//! Channel handshakes establish command order; no sleep establishes test order.

use std::sync::{mpsc, Arc, Mutex};
use std::thread;
use std::time::Duration;
use tmh_core::bus::{BalanceActor, DeviceHub, HubIntervals, MfcActor, TempActor};
use tmh_core::transport::{BusError, MockTransport, Transport};
use tokio::sync::oneshot;

const TEST_TIMEOUT: Duration = Duration::from_secs(3);

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct WireWrite {
    addr: u8,
    raw: i64,
}

impl WireWrite {
    fn is_protective(self) -> bool {
        // The protection batch may begin with a zero command or N2 = 5 L/min.
        (matches!(self.addr, 1 | 3 | 4) && self.raw == 0) || (self.addr == 2 && self.raw == 50)
    }
}

#[derive(Default)]
struct WireLog {
    // None denotes a polling read. Reads count as transactions too: an emergency
    // must precede another ordinary poll, not merely be the next *write*.
    transactions: Vec<Option<WireWrite>>,
    gate_index: Option<usize>,
}

fn decode_write(tx: &[u8]) -> Option<WireWrite> {
    // Input is generated by the production CPL codec, not arbitrary test bytes.
    let text = std::str::from_utf8(tx).ok()?;
    if !text.contains("00XWS,") {
        return None;
    }
    Some(WireWrite {
        addr: u8::from_str_radix(text.get(1..3)?, 16).ok()?,
        raw: text
            .split("W,")
            .nth(1)?
            .split('\x03')
            .next()?
            .parse()
            .ok()?,
    })
}

#[derive(Clone, Copy)]
enum GateAt {
    FirstTransaction,
    FirstWrite,
}

struct BoundaryTransport {
    inner: MockTransport,
    gate_at: GateAt,
    gate_armed: bool,
    entered: mpsc::Sender<Option<WireWrite>>,
    release: mpsc::Receiver<()>,
    log: Arc<Mutex<WireLog>>,
    fail_h2_shutoff: bool,
}

impl Transport for BoundaryTransport {
    fn transact(&mut self, tx: &[u8], deadline: Duration) -> Result<Vec<u8>, BusError> {
        let write = decode_write(tx);
        let gate_here = self.gate_armed
            && (matches!(self.gate_at, GateAt::FirstTransaction) || write.is_some());
        {
            let mut log = self.log.lock().unwrap();
            if gate_here {
                log.gate_index = Some(log.transactions.len());
            }
            log.transactions.push(write);
        }
        if gate_here {
            self.gate_armed = false;
            let _ = self.entered.send(write);
            self.release
                .recv_timeout(TEST_TIMEOUT)
                .map_err(|_| BusError::Timeout)?;
        }
        if self.fail_h2_shutoff && write == Some(WireWrite { addr: 1, raw: 0 }) {
            return Err(BusError::Timeout);
        }
        self.inner.transact(tx, deadline)
    }

    fn read_line(&mut self, deadline: Duration) -> Result<Vec<u8>, BusError> {
        self.inner.read_line(deadline)
    }

    fn reset_buffers(&mut self) -> Result<(), BusError> {
        self.inner.reset_buffers()
    }

    fn reopen(&mut self) -> Result<(), BusError> {
        self.inner.reopen()
    }
}

struct Rig {
    hub: DeviceHub,
    entered: mpsc::Receiver<Option<WireWrite>>,
    release: mpsc::Sender<()>,
    log: Arc<Mutex<WireLog>>,
}

impl Rig {
    fn new(gate_at: GateAt, fail_h2_shutoff: bool) -> Self {
        let (entered_tx, entered) = mpsc::channel();
        let (release, release_rx) = mpsc::channel();
        let log = Arc::new(Mutex::new(WireLog::default()));
        let mfc = MfcActor::new(
            Box::new(BoundaryTransport {
                inner: MockTransport::mfc(),
                gate_at,
                gate_armed: true,
                entered: entered_tx,
                release: release_rx,
                log: log.clone(),
                fail_h2_shutoff,
            }),
            [1, 2, 3, 4],
            [0.1, 1.0, 0.1, 0.1],
            5.0,
            5.0,
        );
        let hub = DeviceHub::spawn(
            TempActor::new(Box::new(MockTransport::temp()), 0, 0.1, false),
            mfc,
            BalanceActor::new(Box::new(MockTransport::balance(100.0))),
            HubIntervals {
                temp: Duration::from_millis(5),
                mfc: Duration::from_millis(5),
                balance: Duration::from_millis(5),
            },
        );
        Self {
            hub,
            entered,
            release,
            log,
        }
    }

    fn wait_for_in_flight_transaction(&self) -> Option<WireWrite> {
        self.entered
            .recv_timeout(TEST_TIMEOUT)
            .expect("MFC transaction reached controlled boundary")
    }

    fn complete_in_flight_transaction(&self) {
        self.release.send(()).expect("MFC boundary still present");
    }

    fn trace(&self) -> Vec<WireWrite> {
        self.log
            .lock()
            .unwrap()
            .transactions
            .iter()
            .flatten()
            .copied()
            .collect()
    }

    fn next_transaction_after_gate(&self) -> Option<Option<WireWrite>> {
        let log = self.log.lock().unwrap();
        log.transactions.get(log.gate_index? + 1).copied()
    }
}

impl Drop for Rig {
    fn drop(&mut self) {
        // Always release a gated bus before DeviceHub::drop joins its threads,
        // including when an assertion panics before the normal release point.
        let _ = self.release.send(());
        self.hub.stop();
    }
}

fn reply<T: Send + 'static>(rx: oneshot::Receiver<T>) -> T {
    let (tx, received) = mpsc::sync_channel(1);
    thread::spawn(move || {
        let _ = tx.send(rx.blocking_recv());
    });
    received
        .recv_timeout(TEST_TIMEOUT)
        .expect("command must finish or explicitly reject")
        .expect("actor must reply")
}

#[test]
fn normal_flow_and_atmosphere_commands_work_before_an_emergency() {
    let rig = Rig::new(GateAt::FirstTransaction, false);
    assert_eq!(rig.wait_for_in_flight_transaction(), None);
    let flow = rig.hub.request_set_flow(0, 3.0);
    let batch = rig.hub.request_set_atmosphere([2.0, 10.0, 0.0, 4.0]);
    rig.complete_in_flight_transaction();
    assert!(reply(flow).is_ok());
    assert!(reply(batch).is_ok());
    assert_eq!(rig.trace().last(), Some(&WireWrite { addr: 4, raw: 400 }));
}

#[test]
fn emergency_preempts_older_ordinary_commands_at_next_transaction_boundary() {
    let rig = Rig::new(GateAt::FirstTransaction, false);
    assert_eq!(rig.wait_for_in_flight_transaction(), None); // Initial PV poll is in flight.
    let flow = rig.hub.request_set_flow(0, 3.0);
    let batch = rig.hub.request_set_atmosphere([2.0, 10.0, 0.0, 4.0]);
    let emergency = rig.hub.request_shutoff_flammable();
    rig.complete_in_flight_transaction();
    assert!(reply(emergency).is_ok());
    let _ = reply(flow);
    let _ = reply(batch);
    let trace = rig.trace();
    let next = rig.next_transaction_after_gate();
    assert!(
        next.is_some_and(|entry| entry.is_some_and(|write| write.is_protective())),
        "next wire transaction must be protective, not an ordinary read/write: next={next:?}, writes={trace:?}"
    );
}

#[test]
fn emergency_interrupts_an_atmosphere_batch_at_its_next_wire_boundary() {
    let rig = Rig::new(GateAt::FirstWrite, false);
    let batch = rig.hub.request_set_atmosphere([3.0, 10.0, 3.0, 3.0]);
    assert_eq!(
        rig.wait_for_in_flight_transaction(),
        Some(WireWrite { addr: 1, raw: 300 })
    );
    let emergency = rig.hub.request_shutoff_flammable();
    rig.complete_in_flight_transaction(); // The already-started H2 transaction may finish.
    assert!(reply(emergency).is_ok());
    let batch_result = reply(batch);
    let trace = rig.trace();
    let next = rig.next_transaction_after_gate();
    assert!(
        next.is_some_and(|entry| entry.is_some_and(|write| write.is_protective())),
        "the next transaction after in-flight H2 must protect; next={next:?}, batch={batch_result:?}, writes={trace:?}"
    );
    assert!(
        batch_result.is_err(),
        "interrupted ordinary batch must report cancellation"
    );
}

#[test]
fn dangerous_commands_already_queued_behind_emergency_cannot_reopen_gas() {
    let rig = Rig::new(GateAt::FirstTransaction, false);
    assert_eq!(rig.wait_for_in_flight_transaction(), None);
    let emergency = rig.hub.request_shutoff_flammable();
    let flow = rig.hub.request_set_flow(0, 3.0);
    let batch = rig.hub.request_set_atmosphere([0.0, 10.0, 0.0, 3.0]);
    rig.complete_in_flight_transaction();
    assert!(reply(emergency).is_ok());
    let flow_result = reply(flow);
    let batch_result = reply(batch);
    let trace = rig.trace();
    assert!(
        flow_result.is_err() && batch_result.is_err(),
        "queued writes reopened gas after emergency: flow={flow_result:?}, batch={batch_result:?}, trace={trace:?}"
    );
    assert!(
        !trace
            .iter()
            .any(|write| matches!(write.addr, 1 | 4) && write.raw > 0),
        "a rejected command must never reach the wire: {trace:?}"
    );
}

#[test]
fn newly_arriving_set_flow_cannot_reopen_gas_after_emergency_acknowledgement() {
    let rig = Rig::new(GateAt::FirstTransaction, false);
    assert_eq!(rig.wait_for_in_flight_transaction(), None);
    let emergency = rig.hub.request_shutoff_flammable();
    rig.complete_in_flight_transaction();
    assert!(reply(emergency).is_ok());
    let before = rig.trace().len();
    let result = reply(rig.hub.request_set_flow(0, 3.0));
    let trace = rig.trace();
    assert!(
        result.is_err(),
        "new H2 command accepted without explicit reset: result={result:?}, trace={trace:?}"
    );
    assert_eq!(trace.len(), before, "blocked command must not emit a write");
}

#[test]
fn newly_arriving_atmosphere_cannot_reopen_co_after_emergency_acknowledgement() {
    let rig = Rig::new(GateAt::FirstTransaction, false);
    assert_eq!(rig.wait_for_in_flight_transaction(), None);
    let emergency = rig.hub.request_shutoff_flammable();
    rig.complete_in_flight_transaction();
    assert!(reply(emergency).is_ok());
    let result = reply(rig.hub.request_set_atmosphere([0.0, 10.5, 0.0, 4.5]));
    let trace = rig.trace();
    assert!(
        result.is_err(),
        "new reduction atmosphere accepted without reset: result={result:?}, trace={trace:?}"
    );
    assert!(
        !trace.iter().any(|write| write.addr == 4 && write.raw > 0),
        "blocked CO command reached wire: {trace:?}"
    );
}

#[test]
fn failed_emergency_acknowledgement_does_not_unlock_set_on_off() {
    let rig = Rig::new(GateAt::FirstTransaction, true);
    assert_eq!(rig.wait_for_in_flight_transaction(), None);
    let initial = rig.hub.request_set_flow(0, 3.0);
    rig.complete_in_flight_transaction();
    assert!(reply(initial).is_ok());
    assert!(
        reply(rig.hub.request_shutoff_flammable()).is_err(),
        "fake H2 device rejects shutoff acknowledgement"
    );
    let before = rig.trace().len();
    let result = reply(rig.hub.request_set_on_off(0, true));
    let trace = rig.trace();
    assert!(
        result.is_err(),
        "failed protection must remain latched: result={result:?}, trace={trace:?}"
    );
    assert_eq!(
        trace.len(),
        before,
        "failed shutdown must not permit an on-command frame"
    );
}

#[test]
fn protection_commands_and_repeated_emergency_remain_available_while_latched() {
    let rig = Rig::new(GateAt::FirstTransaction, false);
    assert_eq!(rig.wait_for_in_flight_transaction(), None);
    let emergency = rig.hub.request_shutoff_flammable();
    rig.complete_in_flight_transaction();
    assert!(reply(emergency).is_ok());
    assert!(reply(rig.hub.request_set_flow(0, 0.0)).is_ok());
    assert!(reply(rig.hub.request_set_atmosphere([0.0, 5.0, 0.0, 0.0])).is_ok());
    assert!(reply(rig.hub.request_shutoff_flammable()).is_ok());
    assert!(rig.trace().iter().all(|write| write.is_protective()));
}
